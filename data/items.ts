export function getItemIconUrl(itemOrId: ItemData | string): string {
  const item = typeof itemOrId === 'string' ? SHOP_ITEMS[itemOrId] : itemOrId;
  if (!item) return '';
  if (item.ddragonId) {
    return `https://ddragon.leagueoflegends.com/cdn/14.24.1/img/item/${item.ddragonId}.png`;
  }
  return '';
}
